#!/usr/bin/env python3
"""Extract a deliberately narrow default-build simulation profile, not an ASM parser."""
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]

def source(path):
    return (ROOT / path).read_text()

def default_lines(path):
    active = True
    stack = []
    for raw in source(path).splitlines():
        line = raw.split(';', 1)[0].strip()
        if line.startswith('if '):
            if line not in ('if DEF(FAITHFUL)', 'if !DEF(FAITHFUL)'):
                raise ValueError(f'Unsupported conditional: {line}')
            stack.append((active, line == 'if !DEF(FAITHFUL)'))
            active = active and stack[-1][1]
        elif line == 'else':
            parent, branch = stack[-1]
            active = parent and not branch
        elif line == 'endc':
            active = stack.pop()[0]
        elif active:
            yield line
    assert not stack

def main():
    types = re.findall(r'^\s*const ([A-Z_]+)', source('constants/type_constants.asm'), re.M)[:19]
    ids = [line.split()[1] for line in default_lines('constants/move_constants.asm') if line.startswith('const ')]
    ids = ids[:ids.index('STRUGGLE') + 1]
    assert ids[0] == 'NO_MOVE'
    crit = {line.split()[1] for line in default_lines('data/moves/critical_hit_moves.asm') if line.startswith('db ') and line != 'db -1'}
    priorities = {name: int(value) for name, value in re.findall(r'db ([A-Z_]+),\s*(-?\d+)', source('data/moves/priorities.asm'))}
    moves = []
    for line in default_lines('data/moves/moves.asm'):
        if not line.startswith('move '):
            continue
        name, effect, power, typ, accuracy, pp, chance, category = [x.strip() for x in line[5:].split(',')]
        supported = effect == 'EFFECT_NORMAL_HIT' and accuracy == '100' and chance == '0' and name not in crit and category in ('PHYSICAL', 'SPECIAL') and priorities.get(name, 0) == 0
        moves.append((name, int(power), types.index(typ), int(pp), int(category == 'SPECIAL'), int(supported)))
    aliases = dict(re.findall(r'^DEF ([A-Z_]+) EQU ([A-Z_]+)$', '\n'.join(default_lines('constants/move_constants.asm')), re.M))
    assert len(moves) == len(ids) - 1 and all(ids[i + 1] == aliases.get(m[0], m[0]) for i, m in enumerate(moves))
    chart = [[16 for _ in types] for _ in types]
    for atk, defense, effect in re.findall(r'db ([A-Z_]+),\s*([A-Z_]+),\s*([A-Z_]+)', source('data/types/type_matchups.asm')):
        chart[types.index(atk)][types.index(defense)] = {'NO_EFFECT': 0, 'NOT_VERY_EFFECTIVE': 8, 'SUPER_EFFECTIVE': 32}[effect]
    paths = ['data/moves/moves.asm', 'constants/move_constants.asm', 'constants/type_constants.asm', 'data/moves/critical_hit_moves.asm', 'data/moves/priorities.asm', 'data/types/type_matchups.asm']
    digest = hashlib.sha256(''.join(source(p) for p in paths).encode()).hexdigest()
    out = ['/* Generated by extract_simulator_data.py. Default non-FAITHFUL profile only. */', f'/* Source SHA256 {digest} */', f'#define MOVE_COUNT {len(moves) + 1}', '#define TYPE_COUNT 19', 'static const Move moves[MOVE_COUNT] = {', '    {"NO_MOVE", 0, 0, 0, 0, 0},']
    out += [f'    {{"{n}", {p}, {t}, {pp}, {c}, {s}}},' for n, p, t, pp, c, s in moves]
    out += ['};', 'static const uint8_t type_chart[TYPE_COUNT][TYPE_COUNT] = {']
    out += ['    {' + ','.join(map(str, row)) + '},' for row in chart]
    out += ['};', '']
    (ROOT / 'tools/trainer_ai/simulator_data.h').write_text('\n'.join(out))
    print(f'Extracted {len(moves)} moves, {sum(m[-1] for m in moves)} supported, source {digest}')

if __name__ == '__main__':
    main()
