#!/usr/bin/env python3
"""Generate/check explicit optional rendering masks from assembled map records.

Generic trainers, pure text commands and no-op decoration qualify. Runtime additionally
protects nearby objects and disables the policy throughout scripts and menus.
This changes presentation only, never object allocation or event flags.
"""
import argparse
import json
import re
from pathlib import Path
from audit_map_slots import read_symbols
from probe_emulator import require

REPO = Path(__file__).resolve().parents[2]


def generate(rom_path, sym_path):
    data = rom_path.read_bytes()
    symbols = read_symbols(sym_path)
    group = number = 0
    constants = []
    for line in (REPO / "constants/map_constants.asm").read_text().splitlines():
        if re.match(r"\s*newgroup\s*(;.*)?$", line):
            group += 1
            number = 0
        match = re.match(r"\s*map_const (\w+),\s*(\d+),\s*(\d+)", line)
        if match:
            number += 1
            constants.append((match[1], group, number, int(match[2]), int(match[3])))
    names = re.findall(r"^\s*map (\w+),", (REPO / "data/maps/maps.asm").read_text(), re.M)
    require(len(names) == len(constants) == 611, "Map inventory changed")
    commands = re.findall(r"^\s*const (\w+)_command\s*$",
                          (REPO / "macros/scripts/events.asm").read_text(), re.M)
    text_commands = {commands.index(name) for name in ("jumptext", "jumptextfaceplayer")}
    show_commands = {commands.index(name) for name in ("showtext", "showtextfaceplayer")}
    masks = [0]
    group_offsets = []
    map_masks = []
    output = ["; Generated by tools/audit_render_policy.py from assembled map objects.",
              "; Pure text, generic trainers and no-op decoration only; near actors stay.",
              "MobileRenderGroupOffsets:"]
    rows = []
    noop = symbols["DoNothingScript"] & 0xffff
    for name, (constant, group, number, width, height) in zip(names, constants):
        require(name.upper().replace("_", "") == constant.replace("_", ""), f"Map order changed: {name}")
        require((width + 6) * (height + 6) <= 1300, f"Block buffer bound: {name}")
        cursor = symbols[name + "_MapScriptHeader"]
        for size in (2, 3, 5, 5, 5):
            cursor += 1 + data[cursor] * size
        count = data[cursor]
        require(count <= 20, f"Object format changed: {name}")
        mask = 0
        eligible = []
        for index in range(1, count + 1):
            obj = data[cursor + 1 + (index - 1) * 13:cursor + 1 + index * 13]
            kind = obj[7] & 15
            script = int.from_bytes(obj[9:11], "little")
            # Placeholder cameras and all custom scripts remain protected.
            pointer = (cursor // 0x4000) * 0x4000 + script - 0x4000 if script >= 0x4000 else script
            pure_text = (kind == 5 and obj[8] in text_commands) or (kind in (0, 6)
                         and data[pointer] in text_commands)
            # A complete text-only script may restore its own facing before
            # ending. Check all opcodes, target and direction, not just a prefix.
            script_bytes = data[pointer:pointer + 7]
            cosmetic_text = (kind in (0, 6) and len(script_bytes) == 7 and
                            script_bytes[0] in show_commands and
                            script_bytes[3] == commands.index("turnobject") and
                            script_bytes[4] == 254 and script_bytes[5] < 4 and
                            script_bytes[6] == commands.index("end"))
            optional = obj[3] != 0x2e and (kind in (3, 7) or pure_text
                       or cosmetic_text
                       or (kind in (0, 6) and script == noop))
            if optional:
                mask |= 1 << index
                eligible.append(index)
        if number == 1:
            group_offsets.append(len(map_masks))
        if mask not in masks:
            masks.append(mask)
        map_masks.append((name, masks.index(mask)))
        rows.append({"map": name, "group": group, "number": number,
                     "objects": count, "optional_render_indices": eligible})
    require(len(masks) <= 256, "Rendering-mask dictionary exceeds one-byte index")
    for offset in group_offsets:
        output.append(f"\tdw MobileRenderMapMasks + {offset}")
    output.append("MobileRenderMapMasks:")
    for name, index in map_masks:
        output.append(f"\tdb {index} ; {name}")
    output.append("MobileRenderMasks:")
    for mask in masks:
        output.append(f"\tdb ${mask & 255:02x}, ${(mask >> 8) & 255:02x}, ${(mask >> 16) & 255:02x}")
    return "\n".join(output) + "\n", rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rom", type=Path, required=True)
    parser.add_argument("--sym", type=Path, required=True)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    source, rows = generate(args.rom, args.sym)
    target = REPO / "mobile_adapter/rom/replaceable.asm"
    if args.write:
        target.write_text(source)
    else:
        require(target.read_text() == source, "Optional rendering masks changed; review and regenerate")
    if args.output:
        args.output.write_text(json.dumps(rows, indent=2) + "\n")
    print(f"Checked {len(rows)} maps; {sum(bool(r['optional_render_indices']) for r in rows)} have optional rendering masks")


if __name__ == "__main__":
    main()
